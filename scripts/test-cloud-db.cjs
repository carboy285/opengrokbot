const { PGlite } = require('@electric-sql/pglite');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
(async () => {
  const db = new PGlite();
  await db.exec(`create role anon; create role authenticated;
    create schema auth; create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    grant usage on schema public,auth to authenticated,anon;
    grant execute on function auth.uid() to authenticated,anon;`);
  await db.exec(fs.readFileSync('supabase/migrations/202611010001_account_relay.sql','utf8'));
  const owner=randomUUID(), other=randomUUID(), host=randomUUID(), phone=randomUUID(), foreign=randomUUID();
  await db.query('insert into auth.users values ($1),($2)',[owner,other]);
  const claim = async uid => {await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[uid]);await db.exec('set role authenticated');};
  const register = (id,kind,key='A'.repeat(43)+'=') => db.query('select public.opengrok_register_device($1,$2,$3,$4,true)',[id,kind,kind,key]);
  await claim(owner);await register(host,'host');await register(phone,'controller');
  assert.equal((await db.query('select * from public.opengrok_devices')).rows.length,2);
  await assert.rejects(()=>db.query('update public.opengrok_devices set available=false'),/permission denied/);
  await assert.rejects(()=>register(host,'host','B'.repeat(43)+'='),/identity cannot be replaced/);
  await assert.rejects(()=>register(host,'controller'),/identity cannot be replaced/);
  const id=randomUUID(), payload='A'.repeat(100);
  const send = (from,to,kind='request',packet=id,body=payload) => db.query('select public.opengrok_send($1,$2,$3,$4,$5)',[packet,from,to,kind,body]);
  await send(phone,host);await send(phone,host); // idempotent retransmission
  assert.equal((await db.query('select * from public.opengrok_poll($1)',[host])).rows.length,1);
  await assert.rejects(()=>send(host,phone,'request'),/Invalid direction/);
  await assert.rejects(()=>send(phone,host,'request',randomUUID(),'A'.repeat(8000041)),/size exceeded/);
  await assert.rejects(()=>db.query('select * from public.opengrok_packets'),/permission denied/);
  await claim(other);await register(foreign,'controller');
  assert.equal((await db.query('select * from public.opengrok_devices')).rows.length,1,'RLS hides another account devices');
  await assert.rejects(()=>register(host,'host'),/identity cannot be replaced/);
  await assert.rejects(()=>send(foreign,host),/Unknown receiving/);
  await assert.rejects(()=>db.query('select * from public.opengrok_poll($1)',[host]),/Unknown device/);
  await db.query("select public.opengrok_ack($1,$2,'request')",[host,id]);
  await claim(owner);
  assert.equal((await db.query('select * from public.opengrok_poll($1)',[host])).rows.length,1,'Other account cannot acknowledge our messages');
  await db.query("select public.opengrok_ack($1,$2,'request')",[host,id]);
  assert.equal((await db.query('select * from public.opengrok_poll($1)',[host])).rows.length,0);
  for(let n=0;n<40;n++)await send(phone,host,'request',randomUUID());
  await assert.rejects(()=>send(phone,host,'request',randomUUID()),/Mailbox full/);
  await db.exec('reset role');await db.exec("update public.opengrok_packets set expires_at=now()-interval '1 second'");
  await claim(owner);
  assert.equal((await db.query('select * from public.opengrok_poll($1)',[host])).rows.length,0,'Expired ciphertext is deleted');
  await db.exec('reset role; set role anon');
  await assert.rejects(()=>db.query('select * from public.opengrok_devices'),/permission denied/);
  await assert.rejects(()=>db.query('select * from public.opengrok_poll($1)',[host]),/permission denied/);
  await db.close();console.log('PASS: migration, account isolation, immutable identities, queue limits, expiry, anonymous denial and idempotency');
})().catch(error=>{console.error(error);process.exit(1)});
