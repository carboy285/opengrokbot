const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('desktop', {
  configureBot:(id,value)=>ipcRenderer.invoke('bot:configure',id,value),
  listModels:provider=>ipcRenderer.invoke('models:list',provider),
  listFiles:id=>ipcRenderer.invoke('files:list',id),
  openBotFolder:id=>ipcRenderer.invoke('files:open-folder',id),
  revealBotFile:(id,name)=>ipcRenderer.invoke('files:reveal',id,name),
  setupStatus:()=>ipcRenderer.invoke('setup:status'),
  scanCLIs:()=>ipcRenderer.invoke('setup:scan'),
  chooseCLI:id=>ipcRenderer.invoke('setup:choose',id),
  choosePath:provider=>ipcRenderer.invoke('setup:path',provider),
  checkLogin:()=>ipcRenderer.invoke('setup:login'),
  completeSetup:()=>ipcRenderer.invoke('setup:complete'),
  send:(id,text)=>ipcRenderer.invoke('chat:send',id,text),
  retry:id=>ipcRenderer.invoke('chat:retry',id),
  stop:id=>ipcRenderer.invoke('chat:stop',id),
  onChange:callback=>{const listener=(_event,value)=>callback(value);ipcRenderer.on('workspace:changed',listener);return()=>ipcRenderer.removeListener('workspace:changed',listener);},
  composioStatus:()=>ipcRenderer.invoke('composio:status'),
  composioConnect:(key,tools)=>ipcRenderer.invoke('composio:connect',key,tools),
  composioRefresh:()=>ipcRenderer.invoke('composio:refresh'),
  composioLink:slug=>ipcRenderer.invoke('composio:link',slug),
  composioRemove:()=>ipcRenderer.invoke('composio:remove'),
  load: () => ipcRenderer.invoke('workspace:load'),
  save: value => ipcRenderer.invoke('workspace:save', value),
  export: text => ipcRenderer.invoke('workspace:export', text),
  openDocs: url => ipcRenderer.invoke('docs:open', url),
  windowAction: action => ipcRenderer.invoke('window:action', action),
  vaultList: () => ipcRenderer.invoke('vault:list'),
  vaultSave: (title, value) => ipcRenderer.invoke('vault:save', title, value),
  vaultRead: id => ipcRenderer.invoke('vault:read', id),
  vaultDelete: id => ipcRenderer.invoke('vault:delete', id)
});
